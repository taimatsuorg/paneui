# Writes packages/tokens/styles/theme-studio.css (Studio style, aligned with the default neutral theme).
# Re-run after changing values here.
#
# Studio shares the pure neutral surfaces, translucent hairlines, status roles, tag palettes and shadows with the
# default theme while keeping heading font declarations in place. Accent and chart variables are omitted
# so data-accent presets and custom accents continue applying cleanly.
from importlib.util import module_from_spec, spec_from_file_location
from pathlib import Path
import re
import sys

sys.dont_write_bytecode = True

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "packages/tokens/styles/theme-studio.css"


def load_theme():
    spec = spec_from_file_location("gen_theme", ROOT / "tooling/scripts/gen-theme.py")
    mod = module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def parse_shadows(block):
    clean = re.sub(r"/\*.*?\*/", "", block, flags=re.S)
    return {m.group(1): re.sub(r"\s+", " ", m.group(2).strip()) for m in re.finditer(r"--([\w-]+):\s*([^;]+);", clean)}


def mode_block(theme, mode):
    source = theme.LIGHT if mode == "light" else theme.DARK
    skip = set(theme.ACC) | {f"chart-{i}" for i in range(1, 9)}
    d = {
        "heading-font": '"Noto Sans Variable", "Noto Sans", "Noto Sans SC Variable", "Noto Sans SC", -apple-system, BlinkMacSystemFont, "Segoe UI", system-ui, "PingFang SC", sans-serif',
        "heading-font-features": "normal",
    }
    for k, v in source.items():
        if k not in skip:
            d[k] = v
    d["image-outline"] = "oklch(100% 0 0 / 0.1)" if mode == "dark" else "oklch(0% 0 0 / 0.1)"
    d.update(parse_shadows(theme.SHADOWS[mode]))
    return d


def render_block(sel, d):
    body = "\n".join(f"  --{k}: {v};" for k, v in d.items())
    return f"{sel} {{\n{body}\n}}\n"


def main():
    theme = load_theme()
    out = [
        "/*\n"
        " * Generated by tooling/scripts/gen-studio.py. Do not edit.\n"
        " * Studio style: pure neutral surfaces, crisp translucent borders and bottom shadow depth. Corners follow the theme radius.\n"
        ' * Switched with data-style="studio" on <html> (or any element). Light and dark both apply.\n'
        " * Import after the theme (and after theme-accents.css when you use it).\n"
        " */\n"
    ]
    for mode, sel in (
        ("light", 'html[data-style="studio"],\n[data-style="studio"]'),
        ("dark", 'html[data-style="studio"].dark,\n.dark [data-style="studio"]'),
    ):
        d = mode_block(theme, mode)
        out.append(render_block(sel, d))
        print(mode, d["muted-foreground"], d["fg-tertiary"], d["border-control"])
    OUT.write_text("\n".join(out))
    print("wrote", OUT.relative_to(ROOT))


if __name__ == "__main__":
    main()
